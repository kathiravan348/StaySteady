// Per-company statement parameters (R-05). A handful of figures per company; the generator derives
// every reported line from them so the three statements agree with each other and across periods.

import type { CurrencyCode } from '../../../shared/types/currency';

export interface StatementSeed {
  readonly currency: CurrencyCode;
  // Latest full-year revenue in millions of the reporting currency.
  readonly revenueMillions: number;
  // Compound annual revenue growth over the five years, as a fraction (0.08 = 8% a year).
  readonly revenueGrowth: number;
  readonly grossMargin: number;
  readonly operatingMargin: number;
  readonly netMargin: number;
  // Total assets as a multiple of revenue: under 1 for an asset-light business, over 10 for a bank.
  readonly assetsToRevenue: number;
  // Shares outstanding in millions. Market capitalisation is price times this, never a stored guess.
  readonly sharesMillions: number;
  readonly equityToAssets: number;
  readonly debtToEquity: number;
  readonly currentRatio: number;
  readonly capexToRevenue: number;
  // Share of net profit paid out as dividends; zero for a company that pays none.
  readonly dividendPayout: number;
  readonly fiscalYearEnd: string;
  // Indian companies publish both; standalone excludes subsidiaries.
  readonly standaloneShareOfRevenue?: number;
  // Index into the annual list (0 is latest) that was restated after publication.
  readonly restatedYearIndex?: number;
  // Years of negative free cash flow, counted back from the latest: a warning flag with evidence.
  readonly negativeFreeCashFlowYears?: number;
  readonly quarterSeasonality?: readonly [number, number, number, number];
}

